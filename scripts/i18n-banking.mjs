let updated = 0;
for (const file of readdirSync(DIR)) {
  if (!file.endsWith(".json")) continue;
  const path = join(DIR, file);
  const locale = file.replace(/\.json$/, "");
  const t = L[locale] ?? en;
  const data = JSON.parse(readFileSync(path, "utf8"));

  data.Pages ??= {};
  data.Pages.import = t.import;
  data.Pages.banking = t.banking;
  data.Pages.expenses ??= {};
  data.Pages.expenses.scanBtn = t.scanBtn;
  data.Nav ??= {};
  data.Nav.user ??= {};
  data.Nav.user.banking = t.navBanking;
  data.Nav.employee ??= {};
  data.Nav.employee.banking = t.navBanking;

  writeFileSync(path, JSON.stringify(data, null, 2) + "\n", "utf8");
  updated++;
  console.log(`${file} <- ${L[locale] ? locale : "en (fallback)"}`);
}
